// audio_output.rs — Desktop audio output bridge for Spark
//
// Approach: a continuous cpal output stream. A hardware-driven audio callback
// pulls f32 samples from a lock-free SPSC ring buffer at the device sample
// rate; the game thread fills that buffer once per visual frame with as many
// samples as real elapsed time calls for. This is the standard streaming model
// used by console emulators and produces gapless audio, unlike playing a fresh
// decoded `Sound` per frame (macroquad's API), which seams/clicks at every
// chunk boundary because it has no sample-accurate scheduling.
//
// Threading: `ringbuf::HeapRb` split into a `Producer` (game thread) and
// `Consumer` (cpal callback thread). The ring buffer is lock-free SPSC, so the
// callback never blocks the audio device. If the producer underruns (game
// stalls), the callback emits silence; if it overruns (we get ahead), excess
// samples are dropped — both are bounded by the ring capacity.
//
// Sample rate: the engine generates directly at the device's sample rate
// (commonly 48000 on macOS), so no resampling is needed — `generate_samples`
// already takes the rate as a parameter.

use std::sync::atomic::{AtomicBool, Ordering};
use std::sync::Arc;

use cpal::traits::{DeviceTrait, HostTrait, StreamTrait};
use cpal::{FromSample, SampleFormat, SizedSample, Stream, StreamConfig};
use ringbuf::traits::{Consumer, Observer, Producer, Split};
use ringbuf::HeapRb;

/// Default sample rate used if the device doesn't report one. Most desktop
/// audio devices run at 44100 or 48000 Hz.
pub const SAMPLE_RATE: u32 = 44100;

/// Ring-buffer capacity in samples. ~0.5 s at 48 kHz — large enough to absorb
/// frame-time jitter and the occasional slow frame without underrunning, small
/// enough to keep audio latency low.
const RING_CAPACITY: usize = 24000;

/// Target amount of buffered audio to keep queued ahead of the callback, in
/// samples (~50 ms at 48 kHz). Each frame we top the buffer up toward this
/// level based on real elapsed time, so the callback always has data to read
/// without the queue growing unbounded.
const TARGET_QUEUED: usize = 2400;

/// Manages the streaming audio output pipeline.
///
/// Holds the cpal stream (kept alive for the duration of playback), the
/// producer half of the ring buffer, and the device sample rate. Audio is
/// generated by the game thread and consumed by cpal's callback thread.
pub struct AudioOutput {
    /// The live output stream. Dropping this stops audio, so it is kept alive
    /// for the lifetime of `AudioOutput`. `None` if no device was available.
    _stream: Option<Stream>,

    /// Producer half of the SPSC ring buffer (game thread writes samples here).
    producer: Option<ringbuf::HeapProd<f32>>,

    /// The device sample rate the stream was opened at. The engine generates
    /// samples at this rate so no resampling is needed.
    device_rate: u32,

    /// Set by `stop()`; the callback drains the ring buffer when it sees it,
    /// so queued audio is discarded instead of playing out.
    flush: Arc<AtomicBool>,

    /// Fractional-sample carryover: `dt * device_rate` rarely lands on a whole
    /// number, so we accumulate the remainder to keep the long-run rate exact.
    sample_accumulator: f64,

    /// Scratch buffer for generated mono samples, reused across frames.
    scratch: Vec<f32>,
}

impl AudioOutput {
    /// Create a new streaming audio output and start the device stream.
    ///
    /// If no output device is available (or the stream fails to build), audio
    /// is silently disabled — the game still runs, just without sound.
    pub fn new() -> Self {
        let flush = Arc::new(AtomicBool::new(false));
        match Self::build_stream(flush.clone()) {
            Some((stream, producer, device_rate)) => {
                let scratch_cap = (device_rate as usize / 10).max(TARGET_QUEUED);
                AudioOutput {
                    _stream: Some(stream),
                    producer: Some(producer),
                    device_rate,
                    flush,
                    sample_accumulator: 0.0,
                    scratch: vec![0.0; scratch_cap],
                }
            }
            None => {
                eprintln!("[spark audio] no output device; audio disabled");
                AudioOutput {
                    _stream: None,
                    producer: None,
                    device_rate: SAMPLE_RATE,
                    flush,
                    sample_accumulator: 0.0,
                    scratch: vec![0.0; SAMPLE_RATE as usize / 10],
                }
            }
        }
    }

    /// Build the cpal output stream and the ring buffer feeding it. Returns the
    /// stream, the producer half and the device sample rate.
    fn build_stream(flush: Arc<AtomicBool>) -> Option<(Stream, ringbuf::HeapProd<f32>, u32)> {
        let host = cpal::default_host();
        let device = host.default_output_device()?;
        let default_config = device.default_output_config().ok()?;
        let sample_format = default_config.sample_format();
        let device_rate = default_config.sample_rate().0;
        let channels = default_config.channels() as usize;
        let config: StreamConfig = default_config.into();

        let rb = HeapRb::<f32>::new(RING_CAPACITY);
        let (producer, consumer) = rb.split();

        // Open the stream in the device's native sample format; the callback
        // converts from our f32 mix. Unusual formats fall back to requesting
        // f32, which most modern devices accept.
        let stream = match sample_format {
            SampleFormat::I16 => open_stream::<i16>(&device, &config, channels, consumer, flush),
            SampleFormat::U16 => open_stream::<u16>(&device, &config, channels, consumer, flush),
            _ => open_stream::<f32>(&device, &config, channels, consumer, flush),
        }
        .ok()?;
        stream.play().ok()?;
        Some((stream, producer, device_rate))
    }

    /// Generate and enqueue audio for a real elapsed wall-clock interval `dt`
    /// (seconds), independent of the game's fixed tick rate.
    ///
    /// The amount generated tracks real time (`dt * device_rate`, with
    /// fractional carryover), topped up toward `TARGET_QUEUED` so the callback
    /// always has a small cushion. The stream plays it gaplessly.
    pub fn play_realtime_audio(&mut self, audio: &mut spark_core::audio::Audio, dt: f64) {
        let producer = match self.producer.as_mut() {
            Some(p) => p,
            None => return, // audio disabled
        };

        // Samples this interval is worth, plus fractional carryover.
        self.sample_accumulator += dt * self.device_rate as f64;
        let mut want = self.sample_accumulator as usize;

        // Top up toward the target cushion if the queue has drained, so a slow
        // first frame or jitter doesn't leave the callback starving.
        let queued = producer.occupied_len();
        if queued < TARGET_QUEUED {
            want = want.max(TARGET_QUEUED - queued);
        }
        if want == 0 {
            return;
        }
        // Bound to the free space and the scratch capacity.
        want = want.min(producer.vacant_len()).min(self.scratch.len());
        if want == 0 {
            // Buffer full — we're ahead of real time; consume the accumulator
            // so it doesn't spiral, and skip this frame.
            self.sample_accumulator = 0.0;
            return;
        }
        self.sample_accumulator -= (self.sample_accumulator as usize).min(want) as f64;

        let buf = &mut self.scratch[..want];
        audio.generate_samples(self.device_rate, buf);
        producer.push_slice(buf);
    }

    /// Stop playback and flush any queued audio. Called when leaving Running
    /// mode (escape, error, stop, run). The stream stays open (kept by
    /// `_stream`) so a subsequent cart can resume without reopening the device;
    /// the callback drains the ring on its next wake, then plays silence.
    pub fn stop(&mut self) {
        self.flush.store(true, Ordering::Release);
        self.sample_accumulator = 0.0;
    }
}

/// Open an output stream whose callback pulls one mono sample from the ring
/// per output frame, converts it to the device sample type `T`, and writes it
/// to every channel. On underrun it writes silence so the device never starves.
fn open_stream<T: SizedSample + FromSample<f32>>(
    device: &cpal::Device,
    config: &StreamConfig,
    channels: usize,
    mut consumer: ringbuf::HeapCons<f32>,
    flush: Arc<AtomicBool>,
) -> Result<Stream, cpal::BuildStreamError> {
    let err_fn = |e| eprintln!("[spark audio] stream error: {}", e);
    device.build_output_stream(
        config,
        move |out: &mut [T], _: &cpal::OutputCallbackInfo| {
            if flush.swap(false, Ordering::AcqRel) {
                consumer.clear();
            }
            for frame in out.chunks_mut(channels) {
                let s = T::from_sample(consumer.try_pop().unwrap_or(0.0));
                for ch in frame.iter_mut() {
                    *ch = s;
                }
            }
        },
        err_fn,
        None,
    )
}
